// Ad-hoc подпись бандла на macOS (afterPack).
//
// Это не 5.2: сертификата здесь нет и Gatekeeper от такой подписи мягче не
// становится — первый запуск по-прежнему через «Открыть» из контекстного меню.
// Подпись нужна ради уведомлений (4.7). Electron 43 шлёт их через
// UNUserNotificationCenter, а тот отказывает приложению, у которого бандл не
// запечатан: `identity: null` в конфиге означает «не подписывать вовсе», и в
// релизе 0.3.0 подписан оказался только бинарник — линкером, с чужим
// идентификатором `Electron` и `Info.plist=not bound`.
//
// Замер 21 августа, три одинаковые сборки в `~/Applications`, один и тот же
// код показа уведомления:
//
//   подписана линкером (как релиз) — `UNErrorDomain error 1`, 3 отказа из 3
//   подписана ad-hoc (`codesign -s -`) — показ с первого раза
//   подписана Apple Development — то же, что ad-hoc
//
// То есть дело не в сертификате, а в самом факте подписи. Опасен здесь не
// отказ, а его вид: `Notification.isSupported()` отвечает `true`, `show()`
// молчит, ошибка приезжает событием `failed`, которого никто не слушает, — и
// приложение выглядит исправным, просто «уведомления не приходят».
//
// Стоит в `afterPack`, а не в `afterSign`: подписи нет, и второй хук не
// зовётся вовсе. Порядок в упаковщике — ресурсы, затем этот хук, затем
// архивы, — поэтому нативный значок из `extraResources` попадает под печать, а
// не после неё.
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'

export default function adhocSign(context) {
  if (context.electronPlatformName !== 'darwin') return
  const app = join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`)
  // Требование к подписи — по идентификатору, а не по отпечатку сборки. По
  // умолчанию ad-hoc пишет `designated => cdhash H"..."`, то есть «этот и
  // только этот бинарник», а Squirrel при установке обновления сверяет новую
  // сборку с требованием работающей: с отпечатком не сойдётся ни одно
  // следующее обновление (5.4), и узналось бы это уже у пользователя.
  //
  // `--deep` Apple не любит, и по делу: правильнее подписывать вложенное
  // первым. Но удостоверения здесь нет — есть печать без него, и для неё
  // порядок безразличен, а перечислять фреймворки Electron руками значит
  // переписывать список на каждой мажорной версии.
  const appId = context.packager.appInfo.id
  execFileSync(
    'codesign',
    [
      '--force',
      '--deep',
      '--sign',
      '-',
      '--identifier',
      appId,
      // Одним аргументом и через `=`: раздельным `-r` codesign ждёт файл с
      // требованиями, а не текст, и падает на первом же пробеле.
      `-r=designated => identifier "${appId}"`,
      app,
    ],
    { stdio: 'inherit' },
  )
}
