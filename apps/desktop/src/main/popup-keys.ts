/**
 * Клавиши попапа (7.2).
 *
 * Ровно одна: `⌘R`. Отдельным модулем, потому что решение здесь проверяемое, а
 * место, где оно применяется (`createPopup` в `index.ts`), — нет: там живой
 * `BrowserWindow`.
 *
 * `⌘R` в Electron по умолчанию **перезагружает окно** — пункт `reload` стоит в
 * меню по умолчанию на всех платформах. Для попапа это не обновление, а стирание:
 * страница поднимается заново, состояние теряется, а данные приезжают те же
 * самые, потому что пересобрать снимок перезагрузка не просит никого. Поэтому
 * ускоритель перехватывается целиком и уходит нашему обновлению.
 */

/** То из `Input` Electron, что нужно для решения. Свой тип — чтобы тест не тянул Electron. */
export interface PopupKey {
  type: string
  key: string
  control: boolean
  meta: boolean
  alt: boolean
  shift: boolean
}

/**
 * Наш ли это `⌘R`.
 *
 * Обе модификаторные клавиши принимаются без разбора платформы: в меню стоит
 * `CmdOrCtrl+R`, то есть перезагружает окно `⌘R` на macOS и `Ctrl+R` на
 * остальных, и пропустить чужой вариант значит оставить окно перезагружаемым
 * там, где мы не смотрели. `⇧⌘R` — тот же случай: это `forceReload` из того же
 * меню, и стирает он ровно так же.
 *
 * `alt` отсекается: сочетание с ним ни на что в меню не назначено, а значит,
 * это чужая клавиша, и присваивать её себе незачем.
 */
export function isRefreshKey(input: PopupKey): boolean {
  if (input.type !== 'keyDown') return false
  if (input.key.toLowerCase() !== 'r') return false
  if (input.alt) return false
  return input.meta || input.control
}
