import type { ReactNode } from 'react'

// Рамка попапа — одна на все пять состояний (2.8). Раньше эти двенадцать строк
// стиля лежали пятью копиями, и правка в одной означала, что четыре попапа
// теперь другого размера, — заметить это можно было только открыв все пять.

/** Ширина попапа из макета (строка 332). Окно создаётся ровно такой. */
export const POPUP_WIDTH = 400
/**
 * Потолок высоты из макета. Именно потолок: высота считается по содержимому, и
 * до 600 дорастает только длинный список агентов. То же число знает main
 * (`POPUP_MAX_HEIGHT`) — оно там про окно, здесь про содержимое, и сойтись им
 * положено по макету, а не по общему импорту: main в вёрстку не ходит.
 */
export const POPUP_MAX_HEIGHT = 600

export interface PopupShellProps {
  children: ReactNode
}

export function PopupShell({ children }: PopupShellProps) {
  return (
    <div
      style={{
        width: POPUP_WIDTH,
        // Потолок ширины — по окну, а не по числу, и это не перестраховка.
        // Окно создаётся ровно макетных 400 точек, но на Windows безрамочное
        // окно отдаёт содержимому на точку меньше: `setContentSize(400, …)`
        // даёт `contentBounds` 399 и `innerWidth` 399 (замер 28 августа,
        // Windows 11 ARM64, dpr 2 — граница окна стоит физический пиксель, то
        // есть полточки, и округляется вверх до целой). Зашитые 400 в такое
        // окно не влезали, и одна лишняя точка разворачивала **обе** полосы
        // прокрутки: на Windows полосы классические и занимают место, поэтому
        // горизонтальная съедала высоту, а под неё вылезала вертикальная — 15
        // точек, поверх интерфейса, у которого прокрутка своя и в другом
        // месте. На macOS полосы наложенные, места не занимают, и тот же
        // лишний пиксель там не виден вовсе — поэтому четыре месяца этого
        // никто не видел.
        //
        // Проценты, а не `width: '100%'`: витрина рисует раму во флексе с
        // `alignItems: flex-start`, где ширина контейнера неопределённая, и
        // `100%` там схлопнулось бы до содержимого. Неопределённый
        // `max-width` в процентах, наоборот, читается как `none` — витрина
        // остаётся макетной, а окно ужимает раму ровно на то, что забрала
        // система.
        maxWidth: '100%',
        // Потолок приезжает переменной: на маленьком экране он ниже макетного,
        // и знает об этом только окно (`useFitWindow`). Значение по умолчанию —
        // для витрины и тестов, где никакого окна нет.
        maxHeight: `var(--popup-max-height, ${POPUP_MAX_HEIGHT}px)`,
        // Граница считается внутрь. Без этого рамка в один пиксель делала
        // содержимое 402×602 в окне 400×600 — и прокручивалось само окно,
        // поверх интерфейса, у которого прокрутка своя и в другом месте.
        boxSizing: 'border-box',
        background: 'var(--bg)',
        border: '1px solid var(--line)',
        borderRadius: 12,
        overflow: 'hidden',
        display: 'flex',
        flexDirection: 'column',
      }}
    >
      {children}
    </div>
  )
}
