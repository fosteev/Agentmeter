/**
 * Пересборка снимка по кнопке и по `⌘R` (7.2).
 *
 * Живёт отдельным модулем, а не внутри компонента, ровно затем, чтобы её можно
 * было прогнать без браузера: тесты рендерера рисуют статическую разметку и
 * событий не доставляют, а проверять здесь надо не вид, а поведение — второе
 * нажатие на время опроса и отказ, который обязан дойти до экрана.
 *
 * Состояние держит вызывающий (`useState` в `main.tsx`), а порядок переходов —
 * этот модуль. Иначе «занято» и «отказало» разъехались бы по двум местам, и
 * кнопка осталась бы крутиться после отказа.
 */

export interface RefreshState {
  /** Идёт пересборка: кнопка мертва и крутится. */
  busy: boolean
  /**
   * Отказ пересборки дословно. Есть — попап уходит в состояние ошибки: прежние
   * числа рядом с прежним «обновлено 2 с назад» после нажатия на кнопку врут
   * дважды.
   */
  failure?: string
}

export const REFRESH_IDLE: RefreshState = { busy: false }

/**
 * Запускалка пересборки: зовёт `reload` и рассказывает о ходе состояниями.
 *
 * Второе нажатие на время опроса не делает ничего — иначе десять кликов дают
 * десять пересборок индекса, и попап встаёт колом ровно там, где его дёргают
 * потому, что он и так подвис. Замок снимается вместе с ответом, каким бы он ни
 * был: отказавшая пересборка обязана повторяться кнопкой «Повторить».
 */
export function createRefresh(
  reload: () => Promise<unknown>,
  onState: (state: RefreshState) => void,
): () => void {
  let busy = false
  return () => {
    if (busy) return
    busy = true
    onState({ busy: true })
    void reload().then(
      () => {
        busy = false
        onState(REFRESH_IDLE)
      },
      (reason: unknown) => {
        busy = false
        onState({ busy: false, failure: describe(reason) })
      },
    )
  }
}

/**
 * Текст отказа — дословно от того, кто отказал.
 *
 * Свой пересказ здесь был бы враньём наоборот: причина известна только main, и
 * «что-то пошло не так» вместо `SQLITE_BUSY` не помогает никому.
 */
function describe(reason: unknown): string {
  const text = reason instanceof Error ? reason.message : String(reason)
  return text.trim() === '' ? String(reason) : text
}
