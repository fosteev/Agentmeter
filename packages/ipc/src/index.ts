/**
 * Запрос-ответ. Ключ — имя канала, `arg` — аргумент, `result` — ответ.
 * Всё сериализуемое структурным клонированием: ни функций, ни классов.
 */
export interface IpcCalls {
  'snapshot:get': { arg: void; result: TraySnapshot }
  /**
   * Вкладка «Сегодня» одним запросом, а не тремя.
   *
   * Итог в шапке, лента, гистограмма и разрез по проектам приезжают вместе
   * потому, что читаются из одного состояния индекса. Разнеси их по каналам — и
   * между двумя ответами успеет отработать вотчер: в шапке будет 344.9M, а
   * сумма строк даст 345.2M, и объяснить это человеку будет нечем.
   */
  'today:get': { arg: TodayFilter; result: DayReport }
  /**
   * Раскрытая строка ленты — та же задача и **тот же период**, что у строки.
   *
   * Период в аргументе не для симметрии: задача, начатая до полуночи и
   * кончившаяся после, попадает в оба дня своими кусками, и лента показывает
   * кусок. Считай карточка задачу целиком — свёрнутая строка и раскрытая под
   * ней карточка показывали бы разные числа про одну задачу, и каждое по себе
   * осталось бы настоящим. На живых логах это 32 сессии из 578, но на них
   * приходится 21.5% расхода: длинные задачи и есть те, что переползают через
   * полночь.
   *
   * `null` — такой задачи в этом периоде нет.
   */
  'task:get': { arg: { sessionId: string; from: number; to: number }; result: TaskCard | null }
  /**
   * Вкладка «Развёртка» одним запросом (4.2).
   *
   * `scope: 'session'` не сужает период, а меняет знаменатель: постоянное
   * делится на число сессий, и человек видит цену **одной** сессии. Сужать
   * период до одной сессии — это карточка задачи (`task:get`), другой экран.
   */
  'breakdown:get': {
    arg: { scope: 'day' | 'session'; from: number; to: number; provider?: Provider; project?: string }
    result: SpendScreen
  }
  /**
   * Вкладка «История» (4.6). `at` — какой день раскрыт в правой колонке; нет —
   * последний день периода с расходом. Период считает main: «неделя» и
   * «30 дней» отсчитываются от сегодняшних суток, а окно о том, где кончается
   * сегодня, не знает — граница дня настраивается (`ui.dayStartsAtHour`).
   */
  'history:get': { arg: { span: HistorySpan; at?: number }; result: HistoryScreen }
  'limits:get': { arg: void; result: LimitReportRow[] }
  'config:get': { arg: void; result: ConfigReport }
  /**
   * Записать правку настроек (3.6).
   *
   * Аргумент — **часть** конфига, а не конфиг целиком: окно правит один
   * тумблер, и отправка всего объекта означала бы, что настройка, изменённая в
   * это же время другим окном или руками в файле, затирается молча.
   *
   * В ответ приезжает тот же отчёт, что у `config:get`, — уже с применённой
   * правкой и с замечаниями, если что-то из присланного не принято. Пустой
   * список замечаний это «принято всё», а не «ошибок не проверяли».
   */
  'config:set': { arg: { patch: DeepPartial<Config> }; result: ConfigReport }
  /**
   * Включить или выключить автозапуск (5.3).
   *
   * Отдельным каналом, а не полем `config:set`: пишется он не в файл настроек,
   * а в операционную систему — в «Объекты входа» на macOS, в реестр на Windows
   * и в `~/.config/autostart` на Linux. Ответ — состояние, **перечитанное у
   * системы** после записи: она вправе не разрешить, и показывать в тумблере
   * желаемое вместо действительного значит врать самым проверяемым способом.
   */
  'startup:set': { arg: { enabled: boolean }; result: ConfigReport }
  /**
   * Поставить или снять хук строки состояния (1.9).
   *
   * Отдельным каналом по той же причине, что автозапуск: пишется он не в наш
   * файл настроек, а в **чужой** — `~/.claude/settings.json`. Отсюда и главное
   * правило канала: звать его вправе только явное действие человека. Поставить
   * хук при старте «чтобы точки копились» значит поправить чужой конфиг без
   * спроса.
   *
   * Ответ — тот же отчёт, уже с перечитанным у файла состоянием: показать в
   * тумблере желаемое вместо действительного здесь так же нельзя, как в
   * автозапуске.
   */
  'statusline:set': { arg: { enabled: boolean }; result: ConfigReport }
  /**
   * Пересчитать вес по журналу прямо сейчас (1.9).
   *
   * Есть отдельно от автоматического пересчёта по той же причине, по которой у
   * автообновления есть кнопка «Проверить»: автоматический идёт раз в пять
   * минут — он читает запросы Claude за все дни журнала, и делать это на каждый
   * снимок нельзя. Пять минут незаметны, пока смотришь на ленту, и мучительны,
   * когда только что поставил хук и хочешь увидеть, сошлось ли.
   *
   * Чего этот канал **не** делает — не заставляет Claude Code позвать хук.
   * Строку состояния рисует он, JSON с процентами приходит из его ответа API, и
   * снаружи этого не вызвать ничем: наш хук, запущенный руками, получил бы
   * пустой stdin и переписал бы снимок пустотой. Кнопка пересчитывает уже
   * собранное, а не добывает новое.
   */
  'usage:refresh': { arg: void; result: ConfigReport }
  /**
   * Включить или выключить запрос лимитов у Anthropic (6.3).
   *
   * Отдельным каналом, а не полем в `config:set`, по той же причине, что и
   * `statusline:set`: это не настройка вида «сколько знаков после запятой», а
   * согласие на сетевой вызов чужими креденшелами. Отдельный канал не даёт
   * включить его попутно, вместе с темой оформления, и оставляет одно место,
   * куда смотреть, когда спросят «кто пошёл в сеть».
   *
   * Включение **не** делает запрос само: ответ приходит с состоянием, каким
   * оно стало, а первый запрос — по кнопке или по таймеру. Иначе тумблер
   * означал бы «включить и немедленно сходить», а человек ещё читает, что он
   * включил.
   */
  'oauth:set': { arg: { enabled: boolean }; result: ConfigReport }
  /**
   * Спросить проценты прямо сейчас (6.3).
   *
   * В отличие от `usage:refresh`, который пересчитывает уже собранное, этот
   * канал **добывает новое** — и потому единственный в продукте, кроме
   * проверки обновлений, кто ходит в сеть по нажатию. При выключенной
   * настройке возвращает состояние как есть и никуда не идёт.
   */
  'oauth:refresh': { arg: void; result: ConfigReport }
  /**
   * Проверить обновления руками (5.4).
   *
   * Есть отдельно от автоматической проверки затем, что автоматическую можно
   * выключить: кнопка «Проверить» обязана работать и тогда — иначе выключенная
   * настройка означала бы «обновлений больше не будет никогда».
   */
  'update:check': { arg: void; result: ConfigReport }
  /**
   * Установить скачанное и перезапуститься. Зовётся только в фазе `ready`:
   * кнопки в других фазах нет, а вызов в них ничего не сделает — ставить нечего.
   */
  'update:install': { arg: void; result: void }
  'index:rebuild': { arg: void; result: void }
  'doctor:get': { arg: void; result: DoctorReport }
  /**
   * Поднять главное окно на нужной вкладке. Уже открытое — показать и увести в
   * фокус, вкладку при этом не переключая: перезагрузка окна ради вкладки стёрла
   * бы его состояние — прокрутку, фильтр, раскрытую задачу.
   */
  'window:open': { arg: { tab: WindowTab }; result: void }
  /**
   * Подогнать окно попапа под содержимое.
   *
   * Высоту знает только рендерер: она складывается из числа живых агентов и
   * окон лимита, но не сводится к ним — строка переносится по длине проекта,
   * шрифт и язык меняют её высоту, и посчитать это в main значило бы завести
   * вторую вёрстку, которая разъедется с первой на ближайшей правке. Поэтому
   * окно присылает измеренную высоту содержимого, а main решает, поместится ли
   * она: прижимает к потолку макета и к рабочей области экрана.
   *
   * Обратного канала нет намеренно: то, что окно **получило** не запрошенную
   * высоту, видно ему самому — содержимое упрётся в край и покажет свой скролл.
   */
  'popup:resize': { arg: { height: number }; result: void }
  'app:quit': { arg: void; result: void }
}

/** Push из main в renderer. Только уведомления, запрашивать данные обратно нельзя. */
export interface IpcEvents {
  'live:update': TraySnapshot
  'index:progress': IndexProgress
  'alert:limit': { provider: Provider; kind: LimitWindow['kind']; usedPercent: number }
  'alert:session': { sessionId: string; tokens: number; reason: 'idle' | 'expensive' | 'question' }
  /**
   * Настройки изменились — тем же отчётом, что отдаёт `config:get`.
   *
   * Событие нужно окнам, которые правку **не** делали: попап и главное окно
   * живут одновременно, и язык с темой у них обязан быть один. Тот, кто
   * отправил `config:set`, получит отчёт ответом и это событие тоже — второй
   * раз применить то же состояние безвредно, а исключение отправителя
   * потребовало бы знать, кто он.
   */
  'config:changed': ConfigReport
  /**
   * Ход обновления (5.4). Отдельным событием, а не через `config:changed`:
   * проценты скачивания приходят десятками, и слать вместе с ними весь отчёт о
   * настройках — значит перерисовывать экран настроек на каждый процент.
   */
  'update:state': UpdateStatus
}

