/**
 * Контракт между main и renderer.
 *
 * Всё общение идёт через две карты: `IpcCalls` — запрос-ответ, `IpcEvents` —
 * push из main. Канал, которого нет в карте, не существует: `ipcRenderer`
 * оборачивается типизированным клиентом, и строковых литералов в коде окна
 * быть не должно. Иначе через полгода никто не скажет, какие каналы живые.
 *
 * Правило про данные: в renderer уходят готовые к показу числа и признак
 * точности. Renderer не считает расход сам — иначе одна и та же цифра
 * окажется посчитанной дважды и разойдётся.
 */
import type { Entrypoint, LimitReportRow, LimitWindow, Provider } from '@agentmeter/core'

/** Агент, работающий прямо сейчас. */
export interface LiveAgent {
  sessionId: string
  provider: Provider
  project: string
  cwd: string
  branch?: string
  model?: string
  entrypoint: Entrypoint
  startedAt: number
  /**
   * думает / ждёт ответа человека / молчит / завершился.
   *
   * Выводится в 2.2 из того, чем кончился транскрипт, а не из тишины:
   * `packages/core/src/live/state.ts`. `idle` — «ход у агента, но движения не
   * видно»; в макете такого состояния нет, точка у него контурная в `tx3`.
   */
  state: 'working' | 'waiting' | 'idle' | 'done'
  /**
   * Когда процесса не стало. Только у `state: 'done'`: строка держится в
   * снимке ещё несколько минут и гаснет, как в макете («завершился 2 мин
   * назад»).
   */
  endedAt?: number
  tokens: number
  /**
   * В расходе есть восстановленные запросы (1.3) — число показывается со
   * знаком `≈`. Без этого поля попап и CLI покажут на одной машине разные
   * числа без объяснения, какое из них точное.
   */
  approximate: boolean
  /** Темп за последние минуты, токенов в минуту. Ноль — темпа нет. */
  rate: number
  /**
   * Заполнение контекстного окна последним запросом (2.6).
   *
   * Здесь стояло голое `contextFill?: number`, и этого мало ровно по той же
   * причине, по которой не хватило голого `LimitWindow` в 2.5: доля без
   * происхождения — это оценка, выданная за факт. Числитель измерен у обоих
   * провайдеров, а знаменатель написал только Codex; у Claude размера окна нет
   * ни в логе, ни в имени модели, и он выводится из наблюдений. Разница между
   * этими двумя случаями — единственное, что окну надо показать.
   *
   * Поля нет вовсе, когда выводить не из чего. Пустое место честнее
   * правдоподобной доли.
   */
  context?: ContextUsage
}

/** Сколько окна занято и насколько мы уверены в его размере. */
export interface ContextUsage {
  /** Занято промптом последнего записанного запроса, токенов. */
  used: number
  /** Размер окна, токенов. */
  window: number
  /**
   * Доля занятого, 0..1. Лежит готовой: `used / window` в рендерере — это
   * третье число, выведенное из двух, и оно разойдётся с CLI на первой правке
   * округления.
   */
  fill: number
  /** `estimate` — размер окна не из лога, а выведен из наблюдавшегося максимума. */
  confidence: 'exact' | 'estimate'
  /** Чем именно оценка — текст для подсказки в интерфейсе. */
  caveat?: string
}

/** Одна цифра с честной пометкой, откуда она взялась. */
export interface Measured {
  value: number
  /**
   * `exact` — прочитано из логов как есть. `reconstructed` — восстановлено
   * арифметикой, погрешность известна. `estimate` — оценка, показывать со
   * штриховкой и знаком ≈.
   */
  confidence: 'exact' | 'reconstructed' | 'estimate'
  /** Что именно не удалось измерить — текст для подсказки в интерфейсе. */
  caveat?: string
}

export interface DayTotals {
  input: Measured
  output: Measured
  cacheWrite: Measured
  cacheRead: Measured
  /**
   * Сумма всех четырёх видов — то самое число в подвале попапа («344.9M»).
   *
   * Лежит здесь готовым не для удобства: сложить четыре поля в рендерере
   * значит посчитать расход второй раз и вывести из четырёх `confidence`
   * пятый — то есть завести в окне собственную арифметику точности, которая
   * разойдётся с CLI на первой же правке. Считает тот, кто считает всё
   * остальное.
   */
  total: Measured
  requests: number
  sessions: number
  /** Подвал попапа: «22 сессии · 8 проектов» (строка 449 макета). */
  projects: number
}

/** То, что показывает попап из трея. */
export interface TraySnapshot {
  /**
   * Момент снимка. Длительности («4 мин», «завершился 2 мин назад») считаются
   * от него, а не от часов рендерера: иначе тест на фикстуре краснеет по
   * календарю, а не по поломке, и «обновлено N с назад» врёт при задержке
   * доставки события.
   */
  at: number
  agents: LiveAgent[]
  /**
   * Окна лимита ровно в том виде, в каком их отдаёт `limitsReport` — с
   * причиной недоступности и прогнозом.
   *
   * Голый `LimitWindow` здесь стоял по недосмотру и терял оба поля, которые
   * попапу и нужны: без `unavailableReason` окно Claude без процента
   * показывать нечем, кроме пустой полосы, а это ровно та ошибка, ради
   * которой затевался продукт; без `forecast` пропадала вторая половина 2.3.
   *
   * Шапка главного окна («CL ≈68%», «CX 5%», строки 576–584) берёт отсюда же:
   * по провайдеру выбирается окно с наибольшим известным процентом, а если
   * известных нет — любое, ради его `unavailableReason`. Отдельного поля под
   * это заведено намеренно **не** было: выбор максимума ничего не вычисляет, он
   * достаёт уже посчитанное число, и разойтись с `nearestLimitPercent` не может
   * — тот и есть максимум этих максимумов.
   */
  limits: LimitReportRow[]
  today: DayTotals
  /** Ближайший к потолку лимит — по нему красится иконка в трее. */
  nearestLimitPercent?: number
  indexing?: IndexProgress
  /**
   * Источники, до которых не удалось добраться (2.8).
   *
   * Пустой массив, а не отсутствие поля: «проблем нет» — это утверждение, и
   * оно должно приезжать явно. Молчание неотличимо от «мы не проверяли», а
   * измерительный продукт, тихо показывающий половину данных как целое, врёт
   * ровно тем способом, ради борьбы с которым он написан.
   */
  problems: SourceProblem[]
  /**
   * Последний агент, которого мы видели, — для состояния «никого нет»
   * (строка 1242 макета: «Никого. Последний — Codex · troy, 18 мин назад»).
   *
   * Его отсутствие вместе с пустым списком живых и означает второе состояние —
   * «агенты ещё не запускались». Это два разных экрана, и различить их можно
   * только здесь: своей истории у окна нет.
   */
  lastAgent?: LastAgent
}

/** Кого видели последним, когда сейчас не работает никто. */
export interface LastAgent {
  provider: Provider
  project: string
  /** Когда сессия закончилась. Длительность считается от `TraySnapshot.at`. */
  endedAt: number
}

/**
 * До чего не удалось добраться и чем это грозит цифрам.
 *
 * `consequence` приезжает готовой фразой не из лени: последствие знает тот, кто
 * знает, что именно не прочиталось, а окно, сочиняющее «наверное, что-то
 * неполное», однажды успокоит там, где успокаивать нельзя.
 */
export interface SourceProblem {
  provider: Provider
  /** Каталог или файл, до которого не добрались. */
  path: string
  /** Код как его отдала ОС: `EACCES`, `ENOENT`. Показывается дословно. */
  code: string
  /** Что это значит для чисел: «цифры Codex за сегодня — неполные». */
  consequence: string
}

export interface IndexProgress {
  phase: 'idle' | 'scanning' | 'parsing' | 'done' | 'error'
  filesDone: number
  filesTotal: number
  /**
   * Байты, а не файлы, — то, что показывает макет («359 / 570 МБ», строка
   * 1219). Файлы рядом остаются: они нужны `doctor`, а мерить прогресс ими
   * нельзя — транскрипты различаются по размеру на три порядка, и полоса,
   * посчитанная по числу файлов, стоит на месте, а потом прыгает.
   */
  bytesDone: number
  bytesTotal: number
  /**
   * Сколько осталось, мс. `null` — пока не из чего считать (первые файлы).
   * Считает main: у него есть темп, а вывести его в окне значит завести вторую
   * арифметику, которая разойдётся с первой.
   */
  etaMs: number | null
  message?: string
}

/* ───────────────────────────────────────────────────────────────────────────
 * Главное окно (M3).
 *
 * Вкладка «Сегодня» — раздел 3 макета (строки 562–784), карточка задачи —
 * раздел 4 (834–909). Три правила задаются здесь один раз и дальше не
 * переизобретаются.
 *
 * **Доли.** Доля, которую видно числом, — «25% дневного расхода», «41%
 * постоянного», «76% чтения кэша», — приезжает посчитанной. Это ровно то
 * деление токенов на токены, из-за которого в 2.6 `ContextUsage.fill` уехал в
 * main. Доля, существующая только как длина полоски внутри своей же диаграммы
 * (столбик часа против самого высокого часа, полоса задачи против самой дорогой
 * задачи), считается в окне: это подгонка под доступную ширину, второго
 * потребителя у неё нет и разойтись ей не с чем. Ровно поэтому у `HourBucket`
 * лежит готовый `total` — без него окно складывало бы провайдерские куски, чтобы
 * найти максимум, а это уже второй счёт расхода.
 *
 * **Фразы.** Готовой приезжает та, чей **состав** знает только main: какие
 * запросы выделены и сколько они стоят вместе (`timelineNote`), что именно не
 * прочиталось и чем это грозит (`SourceProblem.consequence` из 2.8), как
 * трактовать соотношение долей (`SpendSplit.note`). Окно такую фразу собрать не
 * может — у него нет ни входа, ни повода для суждения, и сочинённая им
 * формулировка однажды окажется неверной.
 *
 * Подпись, которая получается подстановкой **уже приехавших** чисел в
 * постоянный шаблон, — обычный текст интерфейса, и собирает её окно: «и ещё 7
 * задач ниже 3.4M», «+ 4 проекта», «22 сессии · 8 проектов» из подвала попапа.
 * Числа в ней форматирует общий форматтер (`renderer/format.ts`), склонения —
 * `Intl.PluralRules` там же. Вынести такую подпись в main значило бы завести в
 * нём вторую реализацию русского счёта и прибить локаль к процессу, который о
 * ней не знает. Границу проводит не наличие цифры в строке, а наличие
 * суждения за ней.
 *
 * **Пометка выделения — это причина, а не флаг.** Столбик таймлайна и строка
 * инструмента красятся в `alarm` по полю `note`, и в нём же лежит объяснение.
 * Голый `boolean` дал бы красный столбик, про который нельзя спросить, чем он
 * красный.
 */

/** Вкладки главного окна — шапка раздела 3 макета (строки 568–573). */
export type WindowTab = 'today' | 'breakdown' | 'history' | 'settings'

export interface TodayFilter {
  from: number
  to: number
  provider?: Provider
  project?: string
  /** Свернуть сабагентов в родительскую задачу. */
  foldSubagents?: boolean
  /**
   * По чему сортировать; порядок всегда по убыванию. Ключей ровно три — те же,
   * что колонки с числами в шапке ленты (строка 614 макета): «Начало»,
   * «Запросы», «Токены». По умолчанию `tokens`, как нарисовано.
   */
  sort?: 'tokens' | 'started' | 'requests'
}

export interface TaskRow {
  sessionId: string
  /**
   * Название, которое дал агент. `null` — названия нет, и это не то же самое,
   * что пустая строка: макет рисует такую задачу иначе (строки 649–651) — тире,
   * серый «Без названия» и первый промпт подписью вместо модели. Схлопнуть это
   * подстановкой «без названия», как делает `query/TaskRow` для колонки CLI,
   * значит сделать два разных вида строки неразличимыми по данным — та же
   * ошибка, что в 2.8 с «пусто» и «никого нет».
   */
  title: string | null
  /** Первый промпт — подпись под «Без названия». Обрезает и кавычит окно. */
  firstPrompt?: string
  project: string
  branch?: string
  provider: Provider
  model?: string
  startedAt: number
  endedAt: number
  /**
   * Колонка «Запросы» — вызовы к API, а не вызовы инструментов. Число живёт
   * рядом с `toolCalls` потому, что это разные величины: 276 запросов при
   * 195 вызовах инструментов — обычная задача.
   */
  requests: number
  toolCalls: number
  tokens: Measured
  /** Сабагенты, свёрнутые внутрь. Наполняется в 3.5. */
  children?: TaskRow[]
}

/** Где кончается видимая часть ленты и начинается хвост (строка 731 макета). */
export interface FoldedTail {
  /**
   * Индекс в `DayReport.tasks`, с которого строки свёрнуты. Сколько их —
   * `tasks.length − from`: это вычитание индексов, а не расхода.
   */
  from: number
  /** Порог: свёрнуто всё, что дешевле. Показывается текстом — «ниже 4M». */
  belowTokens: number
}

/** Столбик гистограммы «Расход по часам» (строки 737–749). */
export interface HourBucket {
  /** Час в той же зоне, в которой нарезан день (`ui.dayStartsAtHour`), 0..23. */
  hour: number
  /** Столбик составной: по куску на провайдера (строка 742 макета). */
  slices: Array<{ provider: Provider; tokens: number }>
  /**
   * Всего за час. Лежит готовым, чтобы окно не складывало куски ради поиска
   * самого высокого столбика — сложение кусков и есть второй счёт расхода.
   */
  total: number
}

/** Строка блока «По проектам» (строки 754–762). */
export interface ProjectRow {
  /** Имя проекта; у свёрнутого хвоста — пусто, слова для него собирает окно. */
  project: string
  tokens: Measured
  /**
   * Чем красить полосу: провайдер, на который пришлось больше токенов. `null` —
   * поровну либо это свёрнутый хвост, и тогда полоса серая (строка 761).
   * Судить «чей это проект» обязан тот, кто видел обе суммы.
   */
  provider: Provider | null
  /** Сколько проектов свёрнуто в эту строку. Есть только у хвоста. */
  folded?: number
}

/** Постоянное против разового — блок «Куда ушло сегодня» (строки 767–777). */
export interface SpendSplit {
  slices: SpendSlice[]
  /**
   * Вывод под полосой — «Почти половина дня ушла на то, что перезагружалось в
   * каждую сессию». Фразу собирает тот, кто посчитал доли.
   */
  note?: string
}

export interface SpendSlice {
  /** `recurring` — префикс, перечитываемый каждым запросом; `marginal` — разовое. */
  kind: 'recurring' | 'marginal'
  tokens: Measured
  /** Доля, 0..1. Видна числом («41%»), поэтому приезжает готовой. */
  share: number
}

/** Всё, что показывает вкладка «Сегодня» за один запрос. */
export interface DayReport {
  /**
   * Период, за который посчитано, — эхо фильтра. По нему окно рисует заголовок
   * дня; без эха оно нарисовало бы дату запроса, а не дату ответа.
   */
  range: { from: number; to: number }
  /**
   * Индекс пуст — ещё ничего не прочитано. Это не «сегодня не работали»: там
   * другие слова, и вывести одно из другого по пустому списку задач нельзя.
   */
  emptyIndex: boolean
  /**
   * За период нет запросов вовсе — **без учёта фильтров** по провайдеру и
   * проекту. Пустой `tasks` при `emptyDay: false` значит «фильтр отсёк всё», и
   * это третий экран с третьими словами.
   */
  emptyDay: boolean
  totals: DayTotals
  /**
   * Задачи, уже отсортированные по `TodayFilter.sort`. Список полный: хвост не
   * вырезан, а помечен — иначе разворачивание свёртки стоило бы второго
   * запроса, а ответ на него пришёл бы из другого состояния индекса.
   */
  tasks: TaskRow[]
  /**
   * Где начинается свёрнутый хвост. `null` — сворачивать нечего **или**
   * сортировка не по расходу: «ниже 4M» на списке, упорядоченном по времени,
   * означало бы дыры посреди ленты.
   */
  folded: FoldedTail | null
  byHour: HourBucket[]
  /** «По проектам», хвост «+ 4 проекта» — последней строкой списка. */
  byProject: ProjectRow[]
  /**
   * «Куда ушло сегодня» — постоянное против разового.
   *
   * Поля нет, пока модель постоянной стоимости не сведена в дневной итог (4.1);
   * блок тогда не рисуется вовсе. Заполнять его нулями нельзя: «на префикс ушло
   * ноль» — это утверждение, и оно ложное.
   */
  split?: SpendSplit
}

/** Столбик таймлайна запросов: высота = токены запроса (строки 851–863). */
export interface TimelinePoint {
  ts: number
  tokens: number
  /**
   * Чем этот запрос выделен — «два скриншота», «компакт контекста». Есть —
   * столбик красится `alarm`, текст уходит в подсказку.
   */
  note?: string
}

/** Один из четырёх видов токенов с долей (строки 866–881). */
export interface TokenSlice {
  kind: 'input' | 'cacheWrite' | 'cacheRead' | 'output'
  tokens: Measured
  /** Доля, 0..1. Видна числом («76%»), поэтому приезжает готовой. */
  share: number
}

/** Раскрытая строка ленты — раздел 4 макета. */
export interface TaskCard {
  task: TaskRow
  /**
   * «25% дневного расхода» — доля от **суток**, а не от периода фильтра:
   * фраза в макете говорит про день, и подставлять в неё неделю нельзя.
   */
  dayShare: number
  timeline: TimelinePoint[]
  /**
   * Подпись под таймлайном — «два запроса со скриншотами — 11.4M вдвоём».
   * Числа в ней уже посчитаны, окно её только показывает.
   */
  timelineNote?: string
  /** Четыре вида токенов, в порядке макета: ввод, запись, чтение, вывод. */
  tokens: TokenSlice[]
  /** Инструменты задачи, по расходу вниз (строки 884–892). */
  tools: BreakdownRow[]
  /**
   * Наблюдение под раскладкой токенов (строка 881). `advice` — вторая половина
   * фразы, тихим цветом; она появится вместе с рекомендациями (4.3), до тех пор
   * её нет вовсе. Совет, сочинённый окном, — ровно то, чего 4.3 существует
   * чтобы избежать.
   */
  note?: { text: string; advice?: string }
  /**
   * Затронутые файлы (строки 893–901) — **изменённые**, а не прочитанные.
   *
   * Слово выбрано не из вкуса: у Codex чтение идёт обычным шеллом и структурой в
   * лог не попадает вовсе, а правка едет заголовком патча. Считай мы чтение —
   * один и тот же список значил бы у Claude «прочитано и изменено», а у Codex
   * «изменено», и различить это по экрану было бы нечем
   * (`packages/core/src/sources/files.ts`).
   *
   * `total` — сколько файлов задача изменила всего, `paths` — сколько их
   * показано; «+ 8» из макета собирает окно вычитанием. Поля может не быть:
   * задача, не тронувшая ни одного файла, — обычное дело.
   */
  files?: { total: number; paths: string[] }
}

export interface BreakdownRow {
  key: string
  label: string
  /** Что именно разложено: тулы, MCP-серверы, скиллы, сабагенты, категории. */
  axis: 'tool' | 'mcp' | 'skill' | 'agent' | 'category'
  /**
   * Разовая стоимость: результаты вызовов, попавшие в промпт. Точность здесь не
   * украшение — через дележ между параллельными вызовами проходит 33% расхода у
   * Claude и 72% у Codex (1.6), и такая строка обязана приезжать оценкой.
   */
  marginal: Measured
  /** Постоянная: то, что лежит в префиксе и перечитывается каждый запрос. */
  recurring: Measured
  calls: number
  /**
   * Чем строка выделена — «6 вызовов со скриншотами». Есть — красится `alarm`
   * (строка 889 макета). Судить, дорого ли это, обязан тот, кто считал.
   */
  note?: string
}

export interface DoctorReport {
  cliVersions: string[]
  unknownRecordTypes: Record<string, number>
  malformedLines: number
  /** Расхождение с эталоном Claude Code, если его удалось посчитать. */
  verify?: { checked: number; exact: number; worstPercent: number }
  problems: string[]
}

/**
 * Запрос-ответ. Ключ — имя канала, `arg` — аргумент, `result` — ответ.
 * Всё сериализуемое структурным клонированием: ни функций, ни классов.
 */
export interface IpcCalls {
  'snapshot:get': { arg: void; result: TraySnapshot }
  /**
   * Вкладка «Сегодня» одним запросом, а не тремя.
   *
   * Итог в шапке, лента, гистограмма и разрез по проектам приезжают вместе
   * потому, что читаются из одного состояния индекса. Разнеси их по каналам — и
   * между двумя ответами успеет отработать вотчер: в шапке будет 344.9M, а
   * сумма строк даст 345.2M, и объяснить это человеку будет нечем.
   */
  'today:get': { arg: TodayFilter; result: DayReport }
  'task:get': { arg: { sessionId: string }; result: TaskCard | null }
  'breakdown:get': {
    arg: { scope: 'day' | 'session'; sessionId?: string; from?: number; to?: number }
    result: BreakdownRow[]
  }
  'limits:get': { arg: void; result: LimitReportRow[] }
  'config:get': { arg: void; result: { config: unknown; problems: string[] } }
  'config:set': { arg: { patch: unknown }; result: { problems: string[] } }
  'index:rebuild': { arg: void; result: void }
  'doctor:get': { arg: void; result: DoctorReport }
  /**
   * Поднять главное окно на нужной вкладке. Уже открытое — показать и увести в
   * фокус, вкладку при этом не переключая: перезагрузка окна ради вкладки стёрла
   * бы его состояние — прокрутку, фильтр, раскрытую задачу.
   */
  'window:open': { arg: { tab: WindowTab }; result: void }
  'app:quit': { arg: void; result: void }
}

/** Push из main в renderer. Только уведомления, запрашивать данные обратно нельзя. */
export interface IpcEvents {
  'live:update': TraySnapshot
  'index:progress': IndexProgress
  'alert:limit': { provider: Provider; kind: LimitWindow['kind']; usedPercent: number }
  'alert:session': { sessionId: string; tokens: number; reason: 'idle' | 'expensive' | 'question' }
  'config:changed': { problems: string[] }
}

export type IpcCallName = keyof IpcCalls
export type IpcEventName = keyof IpcEvents

