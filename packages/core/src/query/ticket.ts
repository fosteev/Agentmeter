/**
 * Ключ тикета из имени ветки (3.7).
 *
 * Правило измерено на живых логах, а не выбрано по вкусу: 616 сессий, 461 с
 * веткой, 29 разных имён.
 *
 * | правило                                     | нашло ключ | ложных     |
 * | --------------------------------------------- | ---------- | ---------- |
 * | `[A-Z][A-Z0-9]{1,9}-\d{1,6}` (принятое)     | 9 сессий   | 0          |
 * | то же без учёта регистра                    | 11 сессий  | 2 сессии   |
 *
 * Разница между строками — ветка `refactor/phase-3-sensors`: правило без учёта
 * регистра объявляет её тикетом `phase-3`. Двух сессий не жалко, а вот разрез
 * «по тикетам», в котором завёлся тикет с именем `phase`, врёт про то, куда
 * ушла работа, — и заметить это можно только зная все ветки наизусть.
 *
 * **Из названия задачи и первого промпта ключ не берётся, и это тоже
 * измерение.** В названиях он нашёлся у пяти сессий, в первом промпте — у 72.
 * Все пять названий сидят на отсоединённом `HEAD`, то есть сверить их не с чем;
 * а первый промпт прячется настройкой приватности (3.6), и выводить из
 * скрытого текста показанное значение — это обход собственного обещания.
 * Упоминание тикета в разговоре вообще не значит, что работа шла по нему:
 * «посмотри, как сделано в GARM-806» — обычная фраза.
 */

/**
 * Ключ вида `GARM-802`, если он есть в имени ветки.
 *
 * Ищется в любом месте имени: у 2 из 9 сессий ветка называется
 * `GARM-664.zigbee` и `SC-248.max_widget` — ключ там с суффиксом, и требование
 * «ветка равна ключу» потеряло бы обе.
 */
const KEY = /\b([A-Z][A-Z0-9]{1,9}-\d{1,6})\b/

export function ticketKey(branch: string | null | undefined): string | null {
  if (!branch) return null
  return KEY.exec(branch)?.[1] ?? null
}
