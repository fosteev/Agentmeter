/**
 * Конфиг приложения: что можно настроить и что считается по умолчанию.
 *
 * Правило одно: в конфиге лежат только те числа, которых нет в логах. Всё, что
 * можно измерить, измеряется, а не спрашивается у пользователя. Потолки плана
 * Claude здесь именно потому, что на диске их нет (см. `docs/plan.md`, раздел
 * про честные ограничения).
 */

import type { LocaleSetting } from '../i18n/locale.ts'

export interface Config {
  /** Где искать логи. Пустой массив — использовать пути по умолчанию для ОС. */
  sources: {
    claudeHome: string | null
    codexHome: string | null
    /** Дополнительные каталоги с логами — на случай нестандартной установки. */
    extra: string[]
  }

  limits: {
    claude: ClaudeLimits
    codex: CodexLimits
    /** Какие окна лимита показывать в попапе (7.5). */
    popup: PopupWindows
  }

  alerts: {
    /** Процент лимита, после которого предупреждаем. */
    warnAtPercent: number
    /** Процент, после которого тревожим всерьёз. */
    dangerAtPercent: number
    /** Сессия дороже этого числа токенов — уведомление. 0 — не уведомлять. */
    sessionTokenAlert: number
    /**
     * Уведомлять, когда агент закончил ход и ждёт человека.
     *
     * Это и есть «ИИ доработал»: ход у человека, а чат жив. Раньше жило вместе
     * со следующим полем под именем `notifyOnIdle`, и разделено не ради
     * дробности — поводы разной ценности. Здесь человека зовут к работе.
     */
    notifyOnWaiting: boolean
    /**
     * Уведомлять, когда сессия завершилась.
     *
     * `done` — это не «агент доработал», а «процесса больше нет»: чаще всего
     * человек сам закрыл чат, и тогда уведомление приходит на его же действие,
     * через секунду после него. Отсюда выключено по умолчанию. У Codex реестра
     * процессов нет вовсе (правило 9 в CLAUDE.md), и `done` там означает всего
     * лишь пять минут тишины в роллауте — повод ещё слабее.
     */
    notifyOnDone: boolean
  }

  /** Экран Workflow: кто в цикле кем был, как выглядит вердикт, где цель (9.2). */
  workflow: WorkflowConfig

  index: {
    /**
     * Следить за логами и дочитывать на лету.
     *
     * Срока хранения здесь нет, и это решение M5, а не пропуск: индекс
     * переживает свой источник. Claude Code удаляет транскрипты сам, и после
     * этого разобранное — единственная запись о расходе; настройка «чистить
     * старше N дней» стирала бы её. Цена измерена: 28.7 МБ индекса на 492 МБ
     * логов, 0.58 МБ в день — см. «Ретеншн индекса» в `docs/roadmap.md`.
     */
    watch: boolean
  }

  /**
   * Окно первичной настройки (7.3). Единственное поле мастера, которого нет в
   * «Настройках»: остальное он пишет теми же путями, что и разделы настроек.
   */
  setup: {
    /**
     * Мастер пройден или пропущен. Дефолт `false` — для первого запуска (файла
     * нет); у существующего файла без ключа загрузчик ставит `true`, иначе
     * мастер увидел бы каждый, кто обновился (`carrySetupCompleted`).
     */
    completed: boolean
  }

  updates: {
    /**
     * Проверять обновления автоматически (5.4).
     *
     * **Единственный сетевой вызов продукта.** Всё остальное читается с диска,
     * поэтому настройка выключает проверку целиком — не «спрашивать, но не
     * скачивать», а не ходить в сеть вовсе.
     */
    auto: boolean
  }

  /**
   * Хук строки состояния Claude Code (1.9).
   *
   * Настоящие проценты окон лимита Claude отдаёт ровно в одном месте — на stdin
   * команде `statusLine`. Хук их туда не спрашивает, а записывает: ни сети, ни
   * чужих токенов это не требует, чем и выбрано.
   *
   * Поля «установлен ли» здесь нет намеренно, и по той же причине, что у
   * автозапуска (`main/startup.ts`): установка живёт в **чужом** файле,
   * `~/.claude/settings.json`, и человек вправе убрать её оттуда руками. Наша
   * копия ответа разошлась бы с правдой молча.
   */
  statusline: {
    /**
     * Что стояло в `statusLine` у пользователя до нас — дословным JSON.
     *
     * Дословным, потому что вернуть надо ровно то, что было: у настройки бывают
     * поля помимо команды (`padding`), и восстановление «по памяти о команде»
     * тихо потеряло бы их. `null` — не стояло ничего.
     */
    previous: string | null
  }

  live: {
    /**
     * Как часто трей пересобирает снимок, мс.
     *
     * Критерий 2.1 — «новая сессия видна < 2 с» — держится именно на этом
     * числе: снимок мгновенный, задержка целиком равна периоду опроса плюс
     * стоимость самого снимка. Ставить сюда 2000 значит промахнуться мимо
     * критерия ровно на цену снимка.
     */
    pollMs: number
    /** Тишина, после которой агент считается простаивающим, мс. */
    idleMs: number
    /**
     * Тишина, после которой сессия Codex перестаёт считаться живой, мс.
     *
     * У Codex реестра процессов нет вовсе, и «жив» там означает «писал
     * недавно». Отсюда отдельный порог: у Claude смерть — факт, здесь догадка.
     */
    codexSilenceMs: number
  }

  privacy: {
    /** Не показывать тексты промптов в интерфейсе — только метаданные. */
    hidePrompts: boolean
    /** Не показывать пути и имена файлов. */
    hidePaths: boolean
  }

  ui: {
    theme: 'system' | 'light' | 'dark'
    /** С какого часа считать начало дня. Пятичасовое окно ходит через полночь. */
    dayStartsAtHour: number
    /**
     * Язык интерфейса. `system` — взять у системы с откатом на английский; до
     * 3.8 здесь лежало зашитое `ru`, и человек с английской системой видел
     * русский интерфейс, не имея способа догадаться, откуда он взялся.
     */
    locale: LocaleSetting
    /**
     * Запомненная геометрия главного окна (3.6, долг 3.1).
     *
     * Нулевая ширина означает «не запомнена»: окно откроется размером по
     * умолчанию. Отдельного флага нет потому, что окна нулевой ширины не
     * бывает, а вот позиция `x: 0, y: 0` — обычный левый верхний угол, и
     * пометить «не задано» ею было бы нельзя.
     *
     * Лежит в конфиге, а не в отдельном файле состояния: другого места для
     * настроек у приложения нет, а заводить второе ради четырёх чисел значит
     * получить два файла, которые расходятся при копировании профиля.
     */
    window: WindowBounds
  }
}

/**
 * Роль субагента в цикле «план → исполнитель → приёмка» (9.2).
 *
 * `unknown` — не четвёртая роль, а честное «правило не нашлось». Субагент без
 * правила не становится исполнителем: доля переделки считается от записей
 * исполнителя, и приписать ему чужие значило бы выдумать знаменатель.
 */
export type WorkflowRole = 'executor' | 'reviewer' | 'planner' | 'explore' | 'unknown'

/** Роли, которые можно назначить правилом. `unknown` назначить нельзя — он остаток. */
export type AssignableRole = Exclude<WorkflowRole, 'unknown'>

/** Вердикт приёмки по голове ответа ревьюера. `none` — ничего не совпало или текста нет. */
export type Verdict = 'accepted' | 'notes' | 'rejected' | 'none'

export interface WorkflowRule {
  /** Шаблон `agentType`: только `*` (любая подстрока), регистр учитывается. */
  match: string
  role: AssignableRole
}

/**
 * Настройки экрана Workflow.
 *
 * **Доли — доли, не проценты.** `target.rework: 0.2` — это 20%, `alerts.overhead:
 * 3` — «втрое». Те же единицы, в которых `workflowReport` (9.3) отдаёт
 * показатели: порог сравнивается с `latest` напрямую, без ×100 и без
 * округления, которое сдвинуло бы срабатывание на границе. Проценты выводит
 * экран (9.5), как и везде в продукте, где число показывается долей.
 */
export interface WorkflowConfig {
  /**
   * Вкладка и уведомления — только при `true`. Включено по умолчанию с 0.6.1:
   * выключенную вкладку не находили вовсе, а у того, кто сабагентов не гоняет,
   * она показывает пустое состояние словами. Уведомления при этом молчат, пока
   * не задан порог (`alerts` — `null`).
   */
  enabled: boolean
  /**
   * Кем считать `agentType`. Правила проверяются по порядку, побеждает первое
   * совпадение, ничего не совпало — `unknown`. Промты субагентов не читаются:
   * роль, угаданная по тексту, — эвристика, которую нечем честно пометить.
   */
  roles: WorkflowRule[]
  /**
   * Регулярки вердикта, флаг `i`, поиск по подстроке (без `^`): голова ответа
   * хранится как написана, с разметкой (`**Принят с оговорками.**`) и ведущими
   * пробелами. Порядок проверки — `rejected → notes → accepted`: «не принят»
   * содержит «принят».
   */
  verdicts: { rejected: string; notes: string; accepted: string }
  /** Размер окна: последние N циклов и последние N сессий (для доли ошибок). */
  window: { cycles: number; sessions: number }
  /** Цель по доле переделки, 0..1. `null` — цели нет, и экран показывает долю без неё. */
  target: { rework: number | null }
  /** Пороги «пора в /retro». `null` — показатель не уведомляет. */
  alerts: { rework: number | null; errorRate: number | null; overhead: number | null }
}

export interface WindowBounds {
  width: number
  height: number
  x: number
  y: number
}

export interface ClaudeLimits {
  /**
   * Потолок пятичасового окна во **взвешенных** токенах — `I + W + O + w·R`.
   *
   * Измеряется, а не выбирается: калибровка 1.9 решает систему
   * `p/100 · cap = I + W + O + w · R` и получает потолок вместе с весом. Руками
   * его не задать, и кнопки «мой план» здесь больше нет — объявленных тарифов
   * в этих единицах не существует, а число, посчитанное от выдуманного
   * потолка, — ровно то враньё, ради борьбы с которым продукт затевался (7.4).
   *
   * `null` — не измерено, и тогда процента у окна нет вовсе.
   */
  fiveHourCap: number | null
  /** Потолок недельного окна, там же и тем же способом. */
  weeklyCap: number | null
  /**
   * Сколько весит прочитанный из кэша токен в лимите подписки.
   *
   * Неизвестно и не выводится из логов: разница между «считать полностью» и
   * «не считать вовсе» — два порядка (339M против 4.3M за сутки на живой
   * машине). Считается вместе с потолками — калибровкой по ответам провайдера
   * (этап 1.9), а не подбирается руками.
   *
   * `null` означает «не откалибровано», и тогда лимиты Claude в интерфейсе
   * помечаются оценкой, а не показываются как факт. Подставлять сюда
   * правдоподобное число вместо признания незнания — ровно то враньё, ради
   * борьбы с которым продукт и затевался.
   */
  cacheReadWeight: number | null
  /**
   * Спрашивать проценты у Anthropic напрямую (6.3).
   *
   * **Второй и последний сетевой вызов продукта**, и единственный, который
   * идёт креденшелами Claude Code. Поэтому `false` по умолчанию: включение —
   * это согласие, а согласие по умолчанию не бывает. Выключенная настройка
   * снимает вызов целиком, а не «спрашивает пореже».
   */
  api: { enabled: boolean }
}

/**
 * Лимиты Codex. Потолков тут нет: проценты приходят точными прямо в логе, и
 * считать их не из чего.
 */
export interface CodexLimits {
  enabled: boolean
  /**
   * Спрашивать проценты у OpenAI напрямую (6.4).
   *
   * Третий и последний сетевой вызов продукта, и `false` по умолчанию по той же
   * причине, что у Claude: включение — это согласие ходить в сеть креденшелами
   * Codex, а согласие по умолчанию не бывает.
   *
   * В отличие от Claude, здесь источник добавляет не сам процент (он в логах
   * есть), а его **свежесть**: в логе процент написан в момент запроса, и после
   * дня без Codex он говорит о позавчерашнем окне.
   */
  api: { enabled: boolean }
}

/**
 * Какие окна лимита рисовать в попапе (7.5).
 *
 * Попап отвечает на один вопрос — «можно ли работать дальше», — и окна, до
 * которых человеку дела нет, отвечают на него шумом: месячное окно Codex у того,
 * кто Codex не запускает, занимает строку рядом с тем, ради чего попап открыли.
 *
 * Три правила, без которых настройка стала бы враньём:
 *
 * 1. **Список окон здесь постоянный, а не по снимку.** Окно появляется в
 *    снимке, когда провайдер о нём заговорил, — и галочка обязана существовать
 *    раньше, иначе первое месячное окно приедет в попап без спроса.
 * 2. **Снятая галочка убирает окно везде, где живёт этот список** — из попапа,
 *    из цвета значка и из уведомлений. Иначе спрятанное окно на 100% красит
 *    значок в тревогу, а причины на экране нет: значок горит, попап спокоен.
 * 3. **Умолчание — показывать всё.** Настройка убирает лишнее у того, кто о ней
 *    попросил; молчаливо спрятанный лимит — это не тишина, а недосказанность.
 */
export interface PopupWindows {
  /**
   * `weeklyModel` — недельное окно, привязанное к модели (7.9). Галочка стоит
   * рядом с двумя другими, хотя окно приезжает только со вторым источником
   * (6.3): список окон в настройках **постоянный**, иначе первое такое окно
   * попало бы в попап без спроса.
   */
  claude: { fiveHour: boolean; weekly: boolean; weeklyModel: boolean }
  /**
   * У Codex видов окна четыре: до CLI 0.145.0 недельное окно приезжало
   * пятичасовым слотом, а `other` — это длина, которой мы не знаем имени
   * (см. пункт 8 в `CLAUDE.md`). Разбирать их по слотам нельзя, поэтому и
   * галочки стоят по видам.
   */
  codex: { fiveHour: boolean; weekly: boolean; monthly: boolean; other: boolean }
}

